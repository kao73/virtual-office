package runner

import (
	"fmt"
	"os"
	"os/exec"
	"strings"
)

// notStartedTurns — сколько шагов прогон вправе сделать, всё ещё считаясь
// не начинавшимся.
//
// Число стартовое и взято с живых прогонов, а не из головы. В архиве этапов 3–4
// до результата не дожили четыре прогона, и порог их разводит верно: один
// оборвался связью на втором шаге, не оставив в папке ни строки, — не начинал;
// три прогона ревьюера сделали от пяти до девяти шагов, выдали разбор
// и не смогли отчитаться — поработали и не справились.
//
// Поимённо, с числами и ценами, они перечислены в docs/notes/claude-cli.md,
// и там же запрос, которым это считается. Здесь их нет намеренно: числа рядом
// с именами тут уже путались, а одно место с таблицей надёжнее двух.
//
// Образцы все с одной машины и с двух этапов подряд, так что число остаётся
// стартовым и ждёт калибровки на живом проекте.
//
// Без числа шагов «след пуст» было бы верно только для implementer'а: ревьюер
// работает без инструментов записи вовсе, а аналитик, тридцать шагов читающий
// репозиторий, следа в рабочей папке тоже не оставляет. Судить их по одной
// лишь папке значило бы объявлять «не начинал» всякий их обрыв.
const notStartedTurns = 2

// LeftTrace — начинал ли прогон работу.
//
// След = коммиты `base..HEAD` ∪ дельта незакоммиченного против снимка старта ∪
// число шагов сверх порога. Объединение, а не пересечение: любого из трёх
// довольно, чтобы сказать «агент работал», и это по существу — вопрос стоит
// не «сколько сделано», а «начинал ли вообще».
//
// Дельта берётся против снимка, а не голый `git status`: рабочая папка
// переиспользуется, и чужая незакоммиченная правка лежит в ней ещё до первого
// шага роли. Тем же снимком судят ограждения.
//
// Считается ровно то, что видит `git status`, и границы у этого свои. Правило
// `.gitignore` проекта-клиента прячет от него поднятое окружение тестов
// и кэши — значит прогон, успевший развернуть `.venv` и не сделавший больше
// ничего, следа в этом источнике не оставит. Такой прогон ловится не папкой,
// а числом шагов: развернуть окружение за два шага не выходит.
//
// Расширять счёт до `--ignored` не стали намеренно: это перекинуло бы часть
// прогонов из «не начинал» в «не справился», то есть начало бы тратить попытки
// там, где раньше не тратили, — а цена такой ошибки выше, чем польза.
//
// Ошибку возвращает только то, из-за чего судить нельзя вовсе. Отсутствие
// снимка ошибкой не считается: прогон мог умереть до того, как раннер его снял.
func LeftTrace(workdir, baseCommit string, turns int) (bool, error) {
	if turns > notStartedTurns {
		return true, nil
	}

	committed, err := hasCommits(workdir, baseCommit)
	if err != nil || committed {
		return committed, err
	}
	return hasNewDirt(workdir)
}

// hasCommits — появились ли коммиты после базы прогона.
func hasCommits(workdir, baseCommit string) (bool, error) {
	if baseCommit == "" {
		// Репозиторий без коммитов: сравнивать не с чем, и это законно —
		// первая задача в пустом проекте выглядит именно так.
		return false, nil
	}
	out, err := exec.Command("git", "-C", workdir,
		"rev-list", "--count", baseCommit+"..HEAD").Output()
	if err != nil {
		return false, fmt.Errorf("коммиты прогона в %s не сосчитаны: %w", workdir, err)
	}
	return strings.TrimSpace(string(out)) != "0", nil
}

// hasNewDirt — появилось ли в папке незакоммиченное сверх того, что лежало
// в ней на старте прогона.
func hasNewDirt(workdir string) (bool, error) {
	snapshot, err := os.ReadFile(BaseStatusPath(workdir))
	if err != nil {
		// Снимка нет — прогон не дожил до его записи, а значит не дожил
		// и до первого шага. Отсутствие снимка само по себе есть свидетельство,
		// и жаловаться на него незачем.
		return false, nil //nolint:nilerr // отсутствие снимка — не беда, а ответ
	}
	now, err := WorktreeStatus(workdir)
	if err != nil {
		return false, err
	}

	was := map[string]bool{}
	for _, line := range strings.Split(string(snapshot), "\n") {
		was[line] = true
	}
	for _, line := range strings.Split(string(now), "\n") {
		if line != "" && !was[line] {
			return true, nil
		}
	}
	return false, nil
}
