// Command validate-result проверяет файл результата по контракту «раннер ↔ агент»
// и говорит агенту, что не так, пока тот ещё жив.
//
// Его зовёт ограждение на событии Stop. Кодов выхода ровно два: 0 — результат
// валиден, 2 — любая беда. Двойка не случайна: Claude Code считает блокирующим
// только её, а всякий другой код — неблокирующей ошибкой, после которой агент
// спокойно завершается. Поэтому и «файла нет», и «неверный вызов» — тоже 2.
//
// Разбор здесь не свой: это та же функция, которой раннер читает результат после
// прогона. Второй парсер разъехался бы с первым — так уже было, когда ограждение
// проверяло лишь наличие поля outcome.
package main

import (
	"fmt"
	"os"

	"github.com/kao73/virtual-office/runner"
)

func main() {
	if len(os.Args) != 2 {
		die("validate-result: нужен ровно один аргумент — путь к файлу результата")
	}
	if _, err := runner.ReadResultFile(os.Args[1]); err != nil {
		die(err.Error() + "\n" + runner.ResultAdvice)
	}
}

// die пишет причину в stderr — оттуда её читает агент — и блокирует завершение.
func die(reason string) {
	fmt.Fprintln(os.Stderr, reason)
	os.Exit(2)
}
