// Command validate-result — детерминированная проверка результата прогона,
// которую агент зовёт сам на событии Stop: не даёт завершиться без валидного
// result.json.
//
// Код выхода ровно два значения: 0 — прошло, 2 — любая беда. Двойка не случайна:
// Claude Code считает блокирующей только её, а всякий другой код — неблокирующей
// ошибкой, после которой агент спокойно завершается. Поэтому и «файла нет»,
// и «неверный вызов» — тоже 2.
//
// Разбор здесь не свой: это тот же код, которым раннер судит прогон после его
// конца. Второй парсер разъехался бы с первым — так уже было, когда проверка
// на Stop смотрела лишь на наличие поля outcome.
package main

import (
	"fmt"
	"os"

	"github.com/kao73/virtual-office/internal/runner"
)

func main() {
	args := os.Args[1:]

	if len(args) != 1 {
		die("validate-result: нужен ровно один аргумент — путь к файлу результата")
	}
	if _, err := runner.ReadResultFile(args[0]); err != nil {
		die(err.Error() + "\n" + runner.ResultAdvice)
	}
}

// die пишет причину в stderr — оттуда её читает агент — и блокирует завершение.
func die(reason string) {
	fmt.Fprintln(os.Stderr, reason)
	os.Exit(2)
}
