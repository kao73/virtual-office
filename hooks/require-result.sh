#!/bin/sh
# Ограждение на событие Stop: не даёт агенту завершиться, не оставив файла результата.
#
# Проверка здесь намеренно грубая и без внешних зависимостей — файл есть, непуст,
# содержит поле outcome. Полную проверку контракта делает раннер после прогона:
# ограждение отвечает только за «агент вообще написал результат».
#
# Путь к файлу результата подставляет адаптер, абсолютным.
# Код выхода 2 блокирует завершение, текст из stderr уходит агенту.

set -u

result="${1:-}"

if [ -z "$result" ]; then
	echo "require-result.sh: не передан путь к файлу результата" >&2
	exit 2
fi

# Выход без результата запрещён, но выйти всегда есть чем: невыполнимая задача —
# это failed, помеха извне — blocked. Иначе агент будет биться об ограждение
# до упора в предел шагов.
advice="Завершиться без него нельзя, но выход есть всегда: если задача не вышла — outcome=failed с описанием того, что уже проверено; если мешает внешнее обстоятельство — outcome=blocked с полем blocker."

if [ ! -s "$result" ]; then
	echo "Ты не записал файл результата $result. Запиши его по схеме из системного промпта. $advice" >&2
	exit 2
fi

if ! grep -q '"outcome"' "$result"; then
	echo "В файле результата $result нет поля outcome. Перезапиши его по схеме из системного промпта. $advice" >&2
	exit 2
fi

exit 0
