#!/bin/sh
# Отладочный хук: записывает окружение, в котором его запустил агент.
#
# Нужен ровно на один вопрос — наследуют ли Stop-хуки окружение процесса агента.
# Проверять это надо, а не помнить: на нём стоят ограждения этапа 4.
#
# Путь к файлу результата адаптер подставляет всем хукам первым аргументом,
# и каталог обмена берётся из него: своего места внутри изоляции скрипт не знает.
set -u

out="$(dirname -- "${1:-.}")/hook-env.txt"
env | sort >"$out"
echo "debug-env.sh: окружение записано в $out" >&2
exit 0
