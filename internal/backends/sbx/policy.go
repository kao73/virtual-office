package sbx

import (
	"context"
	"encoding/json"
	"fmt"
	"os/exec"
	"strings"
	"time"
)

// CanaryHost — хост, которым спрашивают базовую политику машины. Он взят не
// с потолка: `example.com` зарезервирован IANA под документацию, и роли,
// которой он понадобится по делу, не существует. Ответ «сюда пустят» поэтому
// означает ровно одно — пустят куда угодно.
const CanaryHost = "example.com"

// ListCommand и CloseCommand — чем человек смотрит базовую политику и чем её
// закрывает. Раннеру они недоступны: он вправе только добавлять разрешения
// (DESIGN §2.6).
//
// Идентификатор правила не подставляется намеренно: у разрешения, заведённого
// руками, он случайный, и назвать его заранее нельзя. Показывает его `policy ls`.
const (
	ListCommand  = "sbx policy ls"
	CloseCommand = "sbx policy rm network --id <id>"
)

// BasePolicy — базовая политика сети машины: то, что раннер не ставит и поставить
// не может.
//
// Обещание «сеть только по списку роли» держится на ней целиком. Своё правило
// раннер выдаёт песочнице разрешающим, а запрет сильнее разрешения — значит
// закрытое умолчание собрать на уровне песочницы нельзя, и закрывает сеть человек
// на машине один раз. Пока это не сделано, роль без единого домена всё равно
// получит открытую сеть — и узнать об этом ей неоткуда.
//
// Отсюда проверка: раннер не может закрыть сеть, но обязан знать, закрыта ли она,
// и сказать вслух, если нет. См. docs/notes/sbx.md.
type BasePolicy struct {
	// run — вызов sbx. Поле нужно тестам: настоящий CLI подменяется подделкой.
	run func(args ...string) (string, error)
}

// Notice — что сказать человеку о базовой политике машины. Пусто означает,
// что сеть закрыта и сказать нечего.
//
// Ошибка — это «не узнал», и она не то же самое, что «закрыта»: sbx без входа
// в Docker отвечает 401 на любую команду, и принять этот отказ за закрытую сеть
// значило бы выдать незнание за гарантию.
func (p BasePolicy) Notice() (string, error) {
	out, runErr := p.exec("policy", "check", "network", CanaryHost, "--json")

	// allowed — указатель, потому что важно отличить «пустят» от «поля нет».
	// Разбор чужого JSON без этого молча читает любой объект без нужного поля
	// как «не пустят», то есть как гарантию, которой никто не давал.
	// Причины в ответе нет: `allowed: true` приходит голым, без имени правила,
	// которое пустило. Измерено на живой машине — поэтому предупреждение отсылает
	// к `policy ls`, а не пересказывает то, чего ему не сказали.
	var answer struct {
		Allowed *bool `json:"allowed"`
	}
	// Ответ разбирается раньше кода выхода и важнее его: отказ приходит вместе
	// с единицей — `sbx policy check` завершается ею всякий раз, когда «не пустят».
	// Измерено на живой машине; принимать самый частый ответ за неудачу проверки
	// значило бы предупреждать об открытой сети именно там, где она закрыта.
	if err := json.Unmarshal([]byte(out), &answer); err != nil || answer.Allowed == nil {
		if runErr != nil {
			return "", fmt.Errorf("базовая политика сети не прочитана: %w", runErr)
		}
		return "", fmt.Errorf("ответ sbx о базовой политике не разобран: %s", strings.TrimSpace(out))
	}
	if !*answer.Allowed {
		return "", nil
	}

	return fmt.Sprintf("сеть машины открыта: %s разрешён базовой политикой. Список network.allow "+
		"в роли тогда ничего не ограничивает — агент дотянется куда угодно. Чем открыта — `%s`, "+
		"закрыть — снять разрешающее правило (`%s`), см. docs/notes/sbx.md",
		CanaryHost, ListCommand, CloseCommand), nil
}

// exec зовёт sbx: настоящий CLI или подделку из теста.
func (p BasePolicy) exec(args ...string) (string, error) {
	return output(p.run, policyTimeout, args...)
}

// output — вызов sbx, от которого нужно сказанное.
//
// Вывод возвращается и при ненулевом коде выхода: у команд политики код — часть
// ответа, а не только признак беды. Решать, что важнее, — дело вызывающего.
// Подделка из теста имеет ту же подпись и подменяет собой весь вызов.
func output(run func(args ...string) (string, error), timeout time.Duration, args ...string) (string, error) {
	if run != nil {
		return run(args...)
	}

	ctx, cancel := context.WithTimeout(context.Background(), timeout)
	defer cancel()

	out, err := exec.CommandContext(ctx, Executable, args...).CombinedOutput()
	if err != nil {
		return string(out), fmt.Errorf("sbx %s: %w\n%s", strings.Join(args, " "), err, out)
	}
	return string(out), nil
}
