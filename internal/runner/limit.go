package runner

import (
	"fmt"
	"time"
)

// LimitState — состояние окна поставщика на момент прогона.
//
// Перечисление нейтральное: окна и их имена у каждого поставщика свои, а раннеру
// нужно одно — начал ли агент работу и когда окно откроется снова. Перевод
// с языка поставщика делает адаптер, как и с расходом.
type LimitState string

const (
	// LimitUnknown — лог о пределах не сказал ничего или сказал незнакомое.
	// Законное состояние: событие о пределах приходит только после первого
	// ответа API, и прогон, не доживший до него, о них не отчитывается.
	LimitUnknown LimitState = ""
	// LimitAllowed — окно открыто, работа шла обычным порядком.
	LimitAllowed LimitState = "allowed"
	// LimitNearing — окно на исходе: этот прогон прошёл, следующему может
	// не хватить места.
	LimitNearing LimitState = "nearing"
	// LimitReached — окно исчерпано, прогон отвергнут. Работа не начиналась,
	// и к качеству агента это отношения не имеет.
	LimitReached LimitState = "reached"
)

// Limit — что лог прогона сказал о пределах поставщика.
//
// Наблюдение раннера, как и расход: в result.json этого нет и быть не может —
// агент, отвергнутый окном, файла результата не пишет вовсе.
//
// Решений по окну раннер не принимает, но исход отвергнутого прогона от этого
// уже не страдает: работы не было, значит нет и следа, а прогон без следа —
// это not_started, и попытка на него не тратится (см. Termination). Нерешённой
// осталась одна вещь — пауза роли до сброса окна; см. docs/notes/budgets.md.
type Limit struct {
	State LimitState
	// Provider — как состояние назвал сам поставщик. Нужен человеку: перечисление
	// принадлежит поставщику, он вправе его пополнить, и незнакомое значение
	// раннер обязан показать, а не проглотить.
	Provider string
	// Window — какое именно окно (у Claude это five_hour, seven_day и другие).
	// Раннер его не разбирает: имя окна нужно человеку, а не коду.
	Window string
	// ResetsAt — когда окно откроется снова. Нулевое время означает, что
	// поставщик не сказал.
	ResetsAt time.Time
}

// Notice — что сказать человеку о пределах. Пусто — сказать нечего.
//
// Об открытом окне не говорится намеренно: событие есть в каждом логе, и строка
// о нём стояла бы над каждым прогоном офиса, ничего не сообщая.
func (l Limit) Notice() string {
	switch l.State {
	case LimitReached:
		return fmt.Sprintf("окно поставщика (%s) исчерпано: прогон отвергнут, работа не начиналась — "+
			"это предел подписки, а не провал агента; сброс %s", l.Window, l.resets())
	case LimitNearing:
		return fmt.Sprintf("окно поставщика (%s) на исходе: сброс %s", l.Window, l.resets())
	case LimitUnknown:
		if l.Provider == "" {
			return ""
		}
		return fmt.Sprintf("поставщик сообщил о своих пределах незнакомое состояние %q (окно %s): "+
			"понять его раннер не умеет, см. docs/notes/budgets.md", l.Provider, l.Window)
	}
	return ""
}

// resets — когда окно откроется, в человеческом виде.
func (l Limit) resets() string {
	if l.ResetsAt.IsZero() {
		return "неизвестно когда"
	}
	return l.ResetsAt.Local().Format("02.01 15:04")
}
