package runner

import "time"

// Usage — во что обошёлся прогон: деньги, время, шаги.
//
// Тип нейтральный, и это не вежливость к будущим агентам, а условие работы:
// считает расход каждый агент по-своему и говорит о нём на своём языке, а всем,
// кто выше адаптера, нужны одни и те же три числа. Перевод — дело адаптера.
//
// В `result.json` этих полей нет и не будет. Файл результата принадлежит агенту,
// разбор его строгий, а расход — наблюдение раннера за прогоном, а не заявление
// агента о работе. Иначе агент получил бы возможность назвать свою цену.
type Usage struct {
	CostUSD    float64 `json:"cost_usd"`
	DurationMS int     `json:"duration_ms"`
	Turns      int     `json:"turns"`
}

// Known — сказал ли агент о расходе хоть что-нибудь.
//
// Пустое значение — законный ответ: прогон, убитый на середине, итога не оставляет.
// Отличать «не знаю» от «ноль» обязательно: в учёте это разные строки, а в лимитах
// выдуманный ноль означал бы, что дорогая задача бесплатна.
func (u Usage) Known() bool { return u != Usage{} }

// Duration — длительность прогона в удобном для человека виде.
func (u Usage) Duration() time.Duration {
	return time.Duration(u.DurationMS) * time.Millisecond
}
