package runner

import "time"

// Workspace — каталог хоста, который бэкенд обязан отдать агенту.
// Пути внутри изоляции совпадают с хостовыми, переводить их не нужно.
type Workspace struct {
	Path     string
	ReadOnly bool
}

// Launch — описание запуска агента: адаптер его готовит, бэкенд исполняет.
// Тип нейтрален к обоим: адаптер знает устройство конкретного агента, бэкенд —
// устройство изоляции, и друг о друге они не знают ничего.
type Launch struct {
	ID      string        // идентификатор запуска; бэкенд может использовать его для имён
	Argv    []string      // командная строка целиком, Argv[0] — исполняемый файл
	Stdin   string        // что подать процессу на вход
	Workdir string        // рабочая директория процесса
	Timeout time.Duration // предел времени; по исчерпании бэкенд убивает процесс

	// Env задаёт сам запуск: эти переменные нужны в любом окружении,
	// изолированном или нет.
	Env []string
	// HostEnv — окружение запуска без изоляции. Часть переменных воспроизводится
	// с хоста (PATH, LANG), часть подменяется, чтобы агент, бегущий в файловой
	// системе владельца машины, не дотянулся до его хозяйства (HOME).
	// В песочнице он вреден: хостовые пути внутри указывают в пустоту.
	HostEnv []string

	// Workspaces — что отдать агенту. Бэкенд без изоляции их игнорирует:
	// каталоги и так на месте.
	Workspaces []Workspace

	// NetworkAllow — хосты, куда роли разрешено ходить сверх того, что нужно
	// самому агенту. Пусто — ничего сверх. Применяет их бэкенд, у которого сеть
	// вообще управляема; тот, у которого нет, обязан сказать об этом вслух:
	// молчаливое неприменение читалось бы как применённое.
	NetworkAllow []string

	// Ниже — то, что показывает --dry-run: увидеть, что именно получит агент,
	// не запуская его и не тратя токенов.
	SystemPrompt string   // итоговый системный промпт
	UserPrompt   string   // стартовое сообщение
	Settings     string   // сгенерированный settings.json
	Skills       []string // скиллы, видимые агенту
	ConfigDir    string   // изолированный каталог конфигурации
	SecretVars   []string // имена переменных с секретами: их значения не печатаются

	// Cleanup убирает временное хозяйство запуска. Никогда не nil.
	Cleanup func() error

	// Clone включает режим `sbx --clone`: первый Workspaces клонируется
	// в песочницу вместо бинд-маунта — так файловые операции агента идут
	// по собственному диску песочницы, а не по бинд-маунту хоста, у которого
	// разлад с блокировками Comet Native (см. internal/backends/sbx/clone.go).
	// Пусто (nil) — обычный бинд-маунт; бэкенд local это поле не видит и не
	// должен: у него изоляции нет вовсе.
	Clone *CloneSync
}

// CloneSync — то, что бэкенду `sbx --clone` нужно знать сверх Workspaces:
// куда вернуть работу агента и что перенести помимо git.
type CloneSync struct {
	// FetchInto — рабочая папка задачи, куда после прогона подтянуть ветку
	// агента через git fetch+merge --ff-only. Может отличаться от первого
	// Workspaces (тот одноразовый и будет снесён вместе с песочницей) —
	// но Dirs ниже синхронизируется в обе стороны именно с первым Workspaces,
	// не с FetchInto: сегодняшний единственный вызывающий (cmd/run-agent
	// --clone) держит их равными нарочно, и раздельные пути сегодня не
	// поддержаны — .agent/.comet уедут не туда, откуда их читает вызывающий.
	FetchInto string
	// Branch — ветка, которую нужно перемотать вперёд в FetchInto после
	// прогона. Обязана совпадать с тем, что сейчас выкачено в FetchInto —
	// иначе fetchBranch (internal/backends/sbx/clone.go) откажет явно, а не
	// молча перемотает чужую ветку. Пустая ветка — ошибка вызывающего:
	// --clone без неё подтягивать некуда.
	Branch string
	// Dirs — каталоги/файлы вне git относительно первого Workspaces
	// (например, ".agent", ".comet/current-change.json", ".comet/runtime"):
	// git-клон копирует только закоммиченное, а каталог обмена и
	// машинно-локальные части .comet/ исключены из git нарочно
	// (ExcludeAgentDir, ExcludeCometRuntime) — без явного переноса песочница
	// их не увидит вовсе. Не называйте здесь то, что роль коммитит
	// (.comet/config.yaml) — оно и так приедет с git-слиянием, а если
	// назвать, cloneSyncOut положит его на хост раньше слияния и оно откажет.
	Dirs []string
}
