package runner

import (
	"errors"
	"fmt"
	"time"
)

// ErrRunTimeout — прогон убит по таймауту роли.
//
// Ошибка типизированная, а не код возврата, и это по существу. Бэкенды
// возвращают `-1` из четырёх разных мест — не создалась песочница, не создался
// лог, не запустился агент, вышло время, — и по коду эти беды неразличимы.
// А различать обязательно: вышедшее время означает, что агент работал и не успел
// (прогон усечён, попытка не тратится), остальные три — что прогона не было
// вовсе. Сверяется через errors.Is: бэкенд вправе обернуть её своими словами.
var ErrRunTimeout = errors.New("агент не уложился в отведённое время и был остановлен")

// RunTimeout — ошибка прогона, убитого по таймауту роли.
//
// Собирается одной функцией на все бэкенды намеренно. Отличать «работал
// и не успел» от «прогона не было» обязан каждый из них, а формулировать это
// каждому по-своему незачем: сверяется ошибка через errors.Is, и разъехавшиеся
// обёртки однажды разъехались бы и по смыслу. Where — где именно это случилось,
// словами бэкенда; пусто — сказать нечего.
func RunTimeout(timeout time.Duration, where string) error {
	if where == "" {
		return fmt.Errorf("%w: предел роли %s", ErrRunTimeout, timeout)
	}
	return fmt.Errorf("%w: предел роли %s, %s", ErrRunTimeout, timeout, where)
}

// EndReason — что итоговое событие лога сказало о конце прогона.
//
// Перечисление нейтральное: свой словарь конца у каждого агента, а раннеру
// нужно одно — дошёл ли прогон до конца сам. Перевод с языка агента делает
// адаптер, как с расходом и окном поставщика.
//
// Это **подсказка, а не приговор**. Причину раннер определяет по следу работы
// (DESIGN §2.3, «проверять причину, а не следствие»): поле `subtype` у Claude
// Code уже поймано на вранье — при `is_error: true` оно равно `"success"`
// (docs/notes/stage-4-load.md).
type EndReason string

const (
	// EndUnknown — лог о конце не сказал ничего или сказал незнакомое.
	// Законное состояние: прогон, убитый до итогового события, о своём конце
	// не отчитывается.
	EndUnknown EndReason = ""
	// EndCompleted — агент дошёл до конца сам.
	EndCompleted EndReason = "completed"
	// EndMaxTurns — агента срезал предел шагов.
	EndMaxTurns EndReason = "max_turns"
	// EndError — агент сломался на ходу: обрыв связи, отказ API, отвергнутое
	// окно подписки. Работал он при этом или нет, лог не говорит — это видно
	// по следу в рабочей папке, а не отсюда.
	EndError EndReason = "error"
)

// Ending — что лог прогона сказал о его конце.
//
// Наблюдение раннера, как Usage и Limit: в result.json этого нет и быть
// не может — файл результата пишет агент, а о том, чем кончился прогон,
// судит раннер.
type Ending struct {
	Reason EndReason
	// Provider — как конец назвал сам агент, дословно. Нужен человеку:
	// словарь принадлежит поставщику, пополнить его он может без нас,
	// и незнакомое значение раннер обязан показать, а не проглотить.
	Provider string
	// Detail — итоговая строка агента, если он её сказал: «API Error: Unable
	// to connect to API (ECONNRESET)». Человек, открывший тикет, должен видеть,
	// что случилось, не заглядывая в лог прогона на чужой машине.
	Detail string
}

// TerminationKind — чем кончился прогон в глазах раннера.
//
// Три беды с тремя разными следствиями плюс нормальный конец. Разводятся они
// не ради точности отчёта, а потому, что попытка задачи тратится только
// на одну из них.
type TerminationKind string

const (
	// TerminationCompleted — валидный результат есть, прогон состоялся.
	TerminationCompleted TerminationKind = "completed"
	// TerminationNotStarted — результата нет, усечения нет, следа работы нет:
	// агент не начинал. Попытка не тратится, задача возвращается своей роли.
	TerminationNotStarted TerminationKind = "not_started"
	// TerminationTruncated — результата нет, прогон срезан пределом шагов
	// или таймаутом. Попытка не тратится, работа продолжается в той же
	// рабочей папке.
	TerminationTruncated TerminationKind = "truncated"
	// TerminationErrored — результата нет, усечения нет, но след работы есть:
	// агент поработал и сломался. Деньги потрачены, начинать всё равно с нуля,
	// попытка тратится — честно.
	TerminationErrored TerminationKind = "errored"
)

// Termination — чем кончился прогон и почему так решено.
type Termination struct {
	Kind TerminationKind
	// Detail — человеческое объяснение одной строкой. Уезжает в тикет,
	// поэтому пишется для человека, а не для разбора кодом.
	Detail string
}

// Idle — прогон не принёс результата не по вине агента.
//
// Объединяет «не начинал» и «не успел»: следствие у них одно — прогона
// как работы не было, попытку тратить не за что, задача остаётся у своей роли.
// Поэтому и серия у них общая (limits.max_idle_runs): два раздельных счётчика
// чередование обошло бы.
func (t Termination) Idle() bool {
	return t.Kind == TerminationNotStarted || t.Kind == TerminationTruncated
}
