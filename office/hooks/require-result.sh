#!/bin/sh
# Ограждение на событие Stop: не даёт агенту завершиться, не оставив валидного
# файла результата.
#
# Сам скрипт ничего не разбирает. Разбор делает бинарник validate-result — той же
# функцией, которой раннер читает результат после прогона. Пока проверок было две
# (здесь — «есть поле outcome», в раннере — вся схема), они разъехались: агент
# завершался с результатом без next_owner, ограждение пропускало, раннер отвергал,
# и сделанная работа уходила в failed.
#
# Путь к файлу результата подставляет адаптер, абсолютным. Бинарник адаптер кладёт
# рядом с этим скриптом: своего пути внутри изоляции скрипт не знает, а конфиг-
# репозиторий агенту не отдают.
#
# Код выхода 2 блокирует завершение, текст из stderr уходит агенту. Любой другой
# код Claude Code считает неблокирующей ошибкой, поэтому все беды — тоже 2.

set -u

result="${1:-}"
validator="$(dirname -- "$0")/validate-result"

if [ -z "$result" ]; then
	echo "require-result.sh: не передан путь к файлу результата" >&2
	exit 2
fi

if [ ! -x "$validator" ]; then
	echo "require-result.sh: рядом со скриптом нет исполняемого validate-result ($validator), проверить результат нечем." >&2
	exit 2
fi

exec "$validator" "$result"
