# Платформа машины, на которой идёт сборка, именами GoReleaser: os и arch.
# Подключается точкой из scripts/*.sh релизного пути — чтобы пред-гейт
# (check-host-is-target.sh) и гейт личности (check-release-identity.sh)
# отвечали на вопрос «какая это машина» одинаково: разойдись они, пред-гейт
# сказал бы «цель есть», гейт промолчал бы на всех, и релиз уехал бы
# непроверенным. Берётся uname, а не `go env`: значение должно говорить, какой
# бинарник здесь запустится, а GOOS/GOARCH из окружения на это не влияют.
#
# install.sh свою копию этих двух строк держит нарочно: его запускают через
# `curl | sh`, подключать ему нечего.
host_os="$(uname -s | tr '[:upper:]' '[:lower:]')"
case "$(uname -m)" in arm64|aarch64) host_arch=arm64 ;; x86_64|amd64) host_arch=amd64 ;; *) host_arch="$(uname -m)" ;; esac
